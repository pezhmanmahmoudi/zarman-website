import { PDFDocument, PageSizes, rgb, type PDFFont } from "pdf-lib";
import fontkit from "@pdf-lib/fontkit";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

/** Stored at settlement. Never rebuild a receipt from current profiles, rates,
 * recipients or fee settings. No banking credentials or identity documents. */
export type RequestCompletionReceiptSnapshot = {
  version: 1;
  request_id: string;
  transaction_id: string;
  reference_code: string;
  completed_at: string;
  sender_name: string;
  recipient_name: string;
  funding_currency: "AUD" | "IRT";
  funding_total: number | string;
  recipient_currency: "AUD" | "IRT";
  recipient_amount: number | string;
  base_fee_aud: number | string;
  priority_fee_aud: number | string;
  priority_fee_amount: number | string;
  priority_fee_status: string;
  applied_rate: number | string;
  service_tier: "standard" | "priority";
};

export function validateRequestReceipt(value: RequestCompletionReceiptSnapshot): void {
  if (!value || value.version !== 1 || !/^[0-9a-f-]{36}$/i.test(value.request_id)
    || !/^[0-9a-f-]{36}$/i.test(value.transaction_id)
    || !Number.isFinite(Date.parse(value.completed_at))
    || !["standard", "priority"].includes(value.service_tier)
    || !["AUD", "IRT"].includes(value.funding_currency) || !["AUD", "IRT"].includes(value.recipient_currency)) {
    throw new Error("invalid_completion_receipt");
  }
  for (const key of ["reference_code", "sender_name", "recipient_name"] as const) {
    if (typeof value[key] !== "string" || !value[key].trim() || value[key].length > 500 || /[\u0000-\u001f]/.test(value[key])) {
      throw new Error("invalid_completion_receipt");
    }
  }
  for (const key of ["funding_total", "recipient_amount", "base_fee_aud", "priority_fee_aud", "priority_fee_amount", "applied_rate"] as const) {
    if (!["string", "number"].includes(typeof value[key]) || String(value[key]).trim() === "" || !Number.isFinite(Number(value[key])) || Number(value[key]) < 0) {
      throw new Error("invalid_completion_receipt");
    }
  }
  if (Number(value.funding_total) <= 0 || Number(value.recipient_amount) <= 0 || Number(value.applied_rate) <= 0) throw new Error("invalid_completion_receipt");
}

export function receiptAmount(amount: number | string, currency: "AUD" | "IRT"): string {
  return `${currency === "IRT" ? "Toman (IRT)" : "AUD"} ${Number(amount).toLocaleString("en-AU", { minimumFractionDigits: currency === "AUD" ? 2 : 0, maximumFractionDigits: 2 })}`;
}

export function requestReceiptRows(receipt: RequestCompletionReceiptSnapshot): [string, string][] {
  validateRequestReceipt(receipt);
  return [
    ["Reference", receipt.reference_code],
    ["Completed (Sydney time)", new Date(receipt.completed_at).toLocaleString("en-AU", { timeZone: "Australia/Sydney", dateStyle: "medium", timeStyle: "short" })],
    ["Sender", receipt.sender_name],
    ["Recipient", receipt.recipient_name],
    ["Total funding received", receiptAmount(receipt.funding_total, receipt.funding_currency)],
    ["Recipient payout", receiptAmount(receipt.recipient_amount, receipt.recipient_currency)],
    ["Accepted exchange rate", `${Number(receipt.applied_rate).toLocaleString("en-AU")} Toman per AUD`],
    ["Service", receipt.service_tier === "priority" ? "Priority" : "Standard"],
    ["Base fee (AUD equivalent)", receiptAmount(receipt.base_fee_aud, "AUD")],
    ["Express processing fee", receiptAmount(receipt.priority_fee_amount, receipt.funding_currency)],
    ...(receipt.service_tier === "priority" ? [["Express processing fee status at completion", receipt.priority_fee_status.replace(/_/g, " ")] as [string, string]] : []),
  ];
}

/** Bilingual names are kept intact using the site's embedded Persian font.
 * Creation/modification dates are pinned to settlement, and the outbox stores
 * the generated bytes before sending so provider retries are byte-identical. */
export async function renderRequestReceiptPdf(receipt: RequestCompletionReceiptSnapshot): Promise<Uint8Array> {
  const rows = requestReceiptRows(receipt);
  const doc = await PDFDocument.create();
  doc.registerFontkit(fontkit);
  doc.setTitle(`Zarman receipt ${receipt.reference_code}`);
  doc.setAuthor("Zarman Exchange");
  doc.setCreator("Zarman Exchange");
  doc.setProducer("Zarman Exchange");
  doc.setCreationDate(new Date(receipt.completed_at));
  doc.setModificationDate(new Date(receipt.completed_at));
  const [regularBytes, boldBytes, logoBytes] = await Promise.all([
    readFile(join(process.cwd(), "public/fonts/IRANSansX-Regular.ttf")),
    readFile(join(process.cwd(), "public/fonts/IRANSansX-Bold.ttf")),
    readFile(join(process.cwd(), "public/images/logo-email.png")),
  ]);
  const regular = await doc.embedFont(regularBytes, { subset: true });
  const bold = await doc.embedFont(boldBytes, { subset: true });
  const logo = await doc.embedPng(logoBytes);
  const ink = rgb(0.06, 0.09, 0.16), muted = rgb(0.35, 0.40, 0.46), accent = rgb(0.07, 0.37, 0.35);
  let page = doc.addPage(PageSizes.A4);
  const width = page.getWidth();
  let y = 589;
  const drawHeader = () => {
    const logoSize = logo.scaleToFit(110, 114);
    page.drawImage(logo, { x: (width - logoSize.width) / 2, y: page.getHeight() - 34 - logoSize.height, ...logoSize });
    const title = "Completed transfer receipt";
    page.drawText(title, { x: (width - bold.widthOfTextAtSize(title, 19)) / 2, y: 663, font: bold, size: 19, color: ink });
    page.drawLine({ start: { x: 42, y: 620 }, end: { x: width - 42, y: 620 }, color: rgb(0.86, 0.89, 0.94), thickness: 0.7 });
  };
  const wrap = (text: string, font: PDFFont, size: number, maxWidth: number) => {
    const lines: string[] = [];
    let line = "";
    for (const char of text) {
      if (line && font.widthOfTextAtSize(line + char, size) > maxWidth) { lines.push(line); line = ""; }
      line += char;
    }
    if (line) lines.push(line);
    return lines;
  };
  drawHeader();
  for (const [label, value] of rows) {
    const lines = wrap(value, regular, 11, width - 262);
    const labelLines = wrap(label, bold, 10, 164);
    const rowHeight = Math.max(32, Math.max(lines.length, labelLines.length) * 16 + 14);
    if (y - rowHeight < 94) { page = doc.addPage(PageSizes.A4); drawHeader(); y = 589; }
    labelLines.forEach((line, index) => page.drawText(line, { x: 42, y: y - index * 16, font: bold, size: 10, color: muted }));
    lines.forEach((line, index) => page.drawText(line, { x: 224, y: y - index * 16, font: regular, size: 11, color: ink }));
    y -= rowHeight;
    page.drawLine({ start: { x: 42, y: y + 12 }, end: { x: width - 42, y: y + 12 }, color: rgb(0.86, 0.89, 0.90), thickness: 0.5 });
  }
  for (const receiptPage of doc.getPages()) {
    receiptPage.drawText("Issued after verified settlement. Keep this receipt for your records.", { x: 42, y: 60, font: regular, size: 9, color: accent });
    receiptPage.drawText("Zarman Exchange  |  www.zarman.com.au", { x: 42, y: 42, font: regular, size: 9, color: muted });
  }
  return doc.save();
}
